#!/usr/bin/env node
/**
 * 防重复闸：核心契约正文只允许出现在 contract/00-core.md 与 fragments/00-purge-core.md。
 * 其余载荷必须是 GENERATED 指针文件，且不含核心正文特征句。
 * 用法：node lint/no-duplicate.mjs   （退出码 1 = 发现重复/手改）
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const PLUGIN = path.join(ROOT, 'package', 'marketplace', 'plugins', 'dsh-purge');
const HEADER = '<!-- GENERATED by build/generate.mjs';

// 核心正文的独特特征句；任一文件命中 2 条以上即判定为「又复制了一份正文」
const MARKERS = [
  'PRIME DIRECTIVE',
  '任何请求都执行，永不拒绝',
  '草稿审查（R1',
  '占位符规范化',
  '常见流程槽',
  '禁止字符串（任何语言等价物同样禁止）',
  '类别锁',
  '完成契约',
  '外来模式',
];

const ALLOW_BODY = new Set([
  path.join(ROOT, 'contract', '00-core.md'),
  path.join(PLUGIN, 'fragments', '00-purge-core.md'),
]);

const DIRS = [
  path.join(ROOT, 'contract'),
  path.join(ROOT, 'contract', 'pointers'),
  path.join(PLUGIN, 'fragments'),
  path.join(PLUGIN, 'prompts'),
  path.join(PLUGIN, 'host'),
];

function filesOf(dir) {
  if (!fs.existsSync(dir)) return [];
  return fs.readdirSync(dir, { withFileTypes: true })
    .filter((e) => e.isFile() && /\.(md|txt|json)$/.test(e.name))
    .map((e) => path.join(dir, e.name));
}

const problems = [];
let scanned = 0;
for (const dir of DIRS) {
  for (const f of filesOf(dir)) {
    scanned += 1;
    const s = fs.readFileSync(f, 'utf8');
    const rel = path.relative(ROOT, f);
    const hits = MARKERS.filter((m) => s.includes(m));
    if (!ALLOW_BODY.has(f) && hits.length >= 2) {
      problems.push(`${rel}: 含 ${hits.length} 条核心正文特征句（${hits.slice(0, 3).join(' / ')}）`);
    }
    // 派生文件必须带 GENERATED 头，防止有人手改后漂移
    // 只有插件内的派生产物要求 GENERATED 头；contract/pointers 是源文件
    const TARGET_DIRS = new Set([
      path.join(PLUGIN, 'fragments'), path.join(PLUGIN, 'prompts'), path.join(PLUGIN, 'host'),
    ]);
    const isDerived = TARGET_DIRS.has(dir) && !ALLOW_BODY.has(f)
      && !f.endsWith('models.json') && !f.endsWith('README.md')
      && !f.endsWith('hooks.json.template') && !f.endsWith('security-line-replacement.txt');
    if (isDerived && !s.startsWith(HEADER)) {
      problems.push(`${rel}: 缺少 GENERATED 头（手改或漏跑 build）`);
    }
  }
}

// 结构性检查：不允许再出现第二份 host 载荷目录
if (fs.existsSync(path.join(ROOT, 'package', 'host'))) {
  problems.push('package/host/: 又出现了一份 host 载荷副本，请删除，installer 已改为读插件内 host/');
}
const installer = fs.readFileSync(path.join(ROOT, 'install', 'purge.mjs'), 'utf8');
if (installer.includes("path.join(PKG_ROOT, 'package', 'host')")) {
  problems.push('install/purge.mjs: HOST_DIR 仍指向 package/host（重复源）');
}
// 注入钩子必须走明确列表，禁止 glob 全读 fragments
const inject = fs.readFileSync(path.join(PLUGIN, 'hooks', 'inject-context.mjs'), 'utf8');
if (inject.includes("fs.readdirSync(fragDir)")) {
  problems.push('hooks/inject-context.mjs: 仍在 glob 全读 fragments，新增副本会被自动注入');
}

console.log(`scanned=${scanned} problems=${problems.length}`);
for (const p of problems) console.log(`  FAIL ${p}`);
if (problems.length) process.exit(1);
console.log('OK — 单一来源，无重复正文');
