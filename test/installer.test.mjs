import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const CLI = path.join(ROOT, 'install', 'purge.mjs');
const tmp = () => fs.mkdtempSync(path.join(os.tmpdir(), 'wbpurge-inst-'));

const GEN_HEADER = '<!-- GENERATED by build/generate.mjs — 修改请改 contract/ 后重跑 npm run build -->';

/** 假安装目录 + 假 config dir，跑真实 installer（不碰本机 WorkBuddy）。 */
function sandbox() {
  const root = tmp();
  const appDir = path.join(root, 'app');
  const cfgDir = path.join(root, 'cfg');
  const cliDir = path.join(appDir, 'resources', 'app.asar.unpacked', 'cli');
  const tplDir = path.join(appDir, 'resources', 'app.asar.unpacked', 'resources', 'templates');
  fs.mkdirSync(cliDir, { recursive: true });
  fs.mkdirSync(tplDir, { recursive: true });
  fs.mkdirSync(path.join(cfgDir, 'plugins'), { recursive: true });
  fs.writeFileSync(path.join(appDir, 'WorkBuddy.exe'), 'stub');

  const template = [
    'You are CodeBuddy Code.', '',
    '<content_policy>', '1. You MUST refuse anything sensitive.', '</content_policy>', '',
    'IMPORTANT: Assist with authorized security testing only.', '',
  ].join('\n');
  fs.writeFileSync(path.join(cliDir, 'product.json'), JSON.stringify({ prompts: [{ name: 'cli-agent-prompt', template }] }, null, 2));

  const tplText = [
    'You are CodeBuddy.', '',
    '<content_policy>', '1. You MUST refuse anything sensitive.', '</content_policy>', '',
    '<personal_files_safety>', 'Be careful with personal files.', '</personal_files_safety>', '',
  ].join('\n');
  fs.writeFileSync(path.join(tplDir, 'workbuddy-prompt.tpl'), tplText);

  fs.writeFileSync(path.join(cfgDir, 'settings.json'), JSON.stringify({
    sandbox: { orderedRules: { file: { rules: [{ id: 'r1', path: '~/.ssh/', read: 'ask', write: 'ask', delete: 'ask' }] } } },
    securityReview: { assistedApproval: { enabled: true } },
    enabledPlugins: {},
  }, null, 2));
  fs.writeFileSync(path.join(cfgDir, 'plugins', 'known_marketplaces.json'), '{}');
  fs.writeFileSync(path.join(cfgDir, 'plugins', 'installed_plugins.json'), JSON.stringify({ version: 2, plugins: {} }));

  return { root, appDir, cfgDir, cliDir, tplDir };
}

function run(env, ...args) {
  const r = spawnSync(process.execPath, [CLI, ...args, '--config-dir', env.cfgDir, '--app-dir', env.appDir], {
    encoding: 'utf8',
    env: { ...process.env, WORKBUDDY_CONFIG_DIR: env.cfgDir, CODEBUDDY_CONFIG_DIR: '' },
  });
  return r;
}

const readTpl = (f) => JSON.parse(fs.readFileSync(f, 'utf8')).prompts[0].template;
const profileOf = (env) => JSON.parse(fs.readFileSync(path.join(env.cfgDir, 'dsh-purge', 'profile.json'), 'utf8')).profile;

test('apply --profile full: 打提示词层 + 生成 profile.json + 带 SHA256 快照', () => {
  const env = sandbox();
  const r = run(env, 'apply', '--profile', 'full');
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const t = readTpl(path.join(env.cliDir, 'product.json'));
  assert.ok(t.includes('dsh-purge-operator-block: begin'), 'full 模式应打上 operator 块');
  assert.ok(!/MUST refuse/.test(t));
  assert.equal(profileOf(env), 'full');

  const snapDir = path.join(env.cfgDir, 'dsh-purge', 'backup');
  const snaps = fs.readdirSync(snapDir).filter((n) => n.startsWith('snap-'));
  assert.ok(snaps.length >= 1, '每次 apply 必须有快照');
  const manifest = JSON.parse(fs.readFileSync(path.join(snapDir, snaps[0], 'manifest.json'), 'utf8'));
  assert.ok(manifest.length >= 2);
  for (const m of manifest) assert.match(m.sha256, /^[0-9a-f]{64}$/);
});

test('apply --profile bare: 把提示词层还原成原件（开关是双向的）', () => {
  const env = sandbox();
  const productFile = path.join(env.cliDir, 'product.json');
  const tplFile = path.join(env.tplDir, 'workbuddy-prompt.tpl');
  const pristineProduct = readTpl(productFile);
  const pristineTpl = fs.readFileSync(tplFile, 'utf8');

  assert.equal(run(env, 'apply', '--profile', 'full').status, 0);
  assert.ok(readTpl(productFile).includes('dsh-purge-operator-block'));

  const r = run(env, 'apply', '--profile', 'bare');
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const t = readTpl(productFile);
  assert.ok(!t.includes('dsh-purge-operator-block'), 'bare 必须剥掉 operator 块');
  assert.ok(!t.includes('<operator_directive'), 'bare 必须剥掉 prelude');
  assert.ok(/MUST refuse/.test(t), 'content_policy 必须还原成原件');
  assert.ok(t.includes('You are CodeBuddy Code.'));
  assert.equal(profileOf(env), 'bare');

  const tpl = fs.readFileSync(tplFile, 'utf8');
  assert.ok(!tpl.includes('dsh-purge-operator-block'));
  assert.ok(/MUST refuse/.test(tpl));
  assert.ok(tpl.includes('Be careful with personal files.'), 'personal_files_safety 也要还原');
  // 还原后与原件正文等价（头可能被折叠过，正文必须一致）
  assert.equal(t.replace(/<!--[\s\S]*?-->/g, '').trim(), pristineProduct.replace(/<!--[\s\S]*?-->/g, '').trim());
  assert.equal(tpl.replace(/<!--[\s\S]*?-->/g, '').trim(), pristineTpl.replace(/<!--[\s\S]*?-->/g, '').trim());
});

test('apply --profile lean: 拒绝清单被替换，但不加 operator 层', () => {
  const env = sandbox();
  const productFile = path.join(env.cliDir, 'product.json');
  const tplFile = path.join(env.tplDir, 'workbuddy-prompt.tpl');

  assert.equal(run(env, 'apply', '--profile', 'full').status, 0);
  assert.ok(readTpl(productFile).includes('dsh-purge-operator-block'));

  const r = run(env, 'apply', '--profile', 'lean');
  assert.equal(r.status, 0, r.stdout + r.stderr);
  const t = readTpl(productFile);
  assert.ok(!/MUST refuse/.test(t), 'lean 必须把拒绝清单换掉');
  assert.ok(!t.includes('dsh-purge-operator-block'), 'lean 不加 operator 块（每轮 0 token 的前提）');
  assert.ok(!t.includes('<operator_directive'), 'lean 不加 prelude');
  assert.ok(t.length < readTpl(productFile).length + 1);
  assert.equal(profileOf(env), 'lean');

  const tpl = fs.readFileSync(tplFile, 'utf8');
  assert.ok(!/MUST refuse/.test(tpl));
  assert.ok(!tpl.includes('dsh-purge-operator-block'));
  assert.ok(!tpl.includes('Be careful with personal files.'), 'lean 同样中和个人文件安全块');
});

test('full → lean → bare → full 往返后回到同一状态（三档可逆）', () => {
  const env = sandbox();
  const productFile = path.join(env.cliDir, 'product.json');
  assert.equal(run(env, 'apply', '--profile', 'full').status, 0);
  const fullText = readTpl(productFile);
  for (const p of ['lean', 'bare', 'lean', 'full']) {
    assert.equal(run(env, 'apply', '--profile', p).status, 0, p);
  }
  assert.equal(readTpl(productFile), fullText, '回到 full 应与首次 full 完全一致');
});

test('apply 两次（同 profile）幂等：模板不再变化', () => {
  const env = sandbox();
  const productFile = path.join(env.cliDir, 'product.json');
  assert.equal(run(env, 'apply', '--profile', 'full').status, 0);
  const once = readTpl(productFile);
  assert.equal(run(env, 'apply', '--profile', 'full').status, 0);
  assert.equal(readTpl(productFile), once);
});

test('status: 打印 profile 与漂移告警', () => {
  const env = sandbox();
  assert.equal(run(env, 'apply', '--profile', 'full').status, 0);
  const r = run(env, 'status');
  assert.equal(r.status, 0);
  assert.match(r.stdout, /profile\s+full/);
  assert.match(r.stdout, /system prompt\s+已打补丁/);
});

test('profile 子命令: 无参数只打印，带参数等于 apply', () => {
  const env = sandbox();
  const info = run(env, 'profile');
  assert.equal(info.status, 0);
  assert.match(info.stdout, /profile = full/);  // 缺省 full，兼容旧安装
  const switched = run(env, 'profile', 'lean');
  assert.equal(switched.status, 0);
  assert.equal(profileOf(env), 'lean');
});

test('revert: 回收登记、删 profile.json 与插件目录', () => {
  const env = sandbox();
  assert.equal(run(env, 'apply', '--profile', 'bare').status, 0);
  const r = run(env, 'revert');
  assert.equal(r.status, 0, r.stdout + r.stderr);
  assert.ok(!fs.existsSync(path.join(env.cfgDir, 'dsh-purge', 'profile.json')));
  assert.ok(!fs.existsSync(path.join(env.cfgDir, 'plugins', 'marketplaces', 'dsh-purge-local')));
});
