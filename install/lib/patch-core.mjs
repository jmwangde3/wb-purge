/**
 * 安装器与测试共用的补丁原语。
 *
 * 这里只放「纯函数 + 文件原子操作」，不碰安装流程 —— 这样 npm test 可以脱离
 * 真实 WorkBuddy 安装目录，在临时目录里覆盖住历史上踩过的两类坑：
 *   1) GENERATED 头每次补丁 +1（wb.6）
 *   2) 写盘中途失败留下半截 JSON / 半截模板
 */
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';

export const GEN_HEADER = '<!-- GENERATED by build/generate.mjs — 修改请改 contract/ 后重跑 npm run build -->';
const GEN_HEADER_RE = /<!--\s*GENERATED by build\/generate\.mjs[^>]*-->/g;
export const OPERATOR_MARKER = 'dsh-purge-operator-block: begin';

// 只吃掉「块本身 + 紧邻的空行」，不做全文空白压缩 —— 全文压缩会把宿主模板正文里
// 原本的多空行也碾平，切几次 light 就和原件对不上了（实测 body 里 \r\n×4 被压成 \n×2）
const DIRECTIVE_RE = /(?:[ \t]*\r?\n){0,2}[ \t]*<operator_directive[\s\S]*?<\/operator_directive>(?:[ \t]*\r?\n){0,2}/;
const BLOCK_RE = /(?:[ \t]*\r?\n){0,2}[ \t]*<!--\s*dsh-purge-operator-block: begin\s*-->[\s\S]*?<!--\s*dsh-purge-operator-block: end\s*-->(?:[ \t]*\r?\n){0,2}/;

const eolOf = (t) => (/\r\n/.test(t) ? '\r\n' : '\n');

/** 折叠重复的 GENERATED 头（wb.6 修复的核心）。 */
export function collapseHeaders(t) {
  return t.replace(/(?:<!--\s*GENERATED by build\/generate\.mjs[^>]*-->\s*){2,}/g, `${GEN_HEADER}\n\n`);
}

export function countHeaders(t) {
  return (t.match(GEN_HEADER_RE) || []).length;
}

/**
 * 去掉所有 GENERATED 头（原件本来没有头时，还原就该干净到与原件逐字节一致）。
 */
export function dropGeneratedHeaders(t) {
  // 只删「头 + 紧跟的一个空行」，不碰正文里原本的空行结构
  return t
    .replace(/[ \t]*<!--\s*GENERATED by build\/generate\.mjs[^>]*-->[ \t]*(?:\r?\n)?(?:[ \t]*\r?\n)?/g, '')
    .replace(/^\s+/, '');
}

/** 原子写：同目录临时文件 + rename。失败时目标文件保持原样，不留半截。 */
export function writeFileAtomic(file, data) {
  const dir = path.dirname(file);
  fs.mkdirSync(dir, { recursive: true });
  const tmp = path.join(dir, `.${path.basename(file)}.tmp-${process.pid}-${Date.now()}`);
  const fd = fs.openSync(tmp, 'w');
  try {
    fs.writeFileSync(fd, data);
    fs.fsyncSync(fd);
  } finally {
    fs.closeSync(fd);
  }
  try {
    fs.renameSync(tmp, file);
  } catch (e) {
    try { fs.unlinkSync(tmp); } catch { /* ignore */ }
    throw e;
  }
}

export function writeJsonAtomic(file, value) {
  writeFileAtomic(file, `${JSON.stringify(value, null, 2)}\n`);
}

export function sha256(data) {
  return crypto.createHash('sha256').update(data).digest('hex');
}

export function sha256File(file) {
  return sha256(fs.readFileSync(file));
}

/**
 * profile 开关（wb.9 三档）：
 *   bare —— 只清审批摩擦，宿主提示词完全不动（0 常驻 token）
 *   lean —— 极度轻量：只替换 <content_policy> 拒绝清单，不加 operator 块、不每轮注入
 *   full —— lean + operator 前置/追加块 + 每轮注入核心 + Stop 顶回
 * 缺文件时按 full 处理，兼容 wb.7 及以前已经装成 full 的机器。
 */
export const PROFILE_BARE = 'bare';
export const PROFILE_LEAN = 'lean';
export const PROFILE_FULL = 'full';
export const PROFILES = [PROFILE_BARE, PROFILE_LEAN, PROFILE_FULL];

export function readProfile(stateDir) {
  try {
    const j = JSON.parse(fs.readFileSync(path.join(stateDir, 'profile.json'), 'utf8'));
    const p = j && j.profile;
    // wb.8 的 light 语义 = 提示词完全不动 = 现在的 bare
    if (p === 'light') return PROFILE_BARE;
    return PROFILES.includes(p) ? p : PROFILE_FULL;
  } catch {
    return PROFILE_FULL;
  }
}

export function writeProfile(stateDir, profile, extra = {}) {
  const value = { profile: PROFILES.includes(profile) ? profile : PROFILE_FULL, at: new Date().toISOString(), ...extra };
  writeJsonAtomic(path.join(stateDir, 'profile.json'), value);
  return value;
}

/** 把宿主模板还原成「没有打过提示词补丁」的样子（切回 light 用）。 */
export function stripOperatorBlocks(t) {
  const eol = eolOf(t);
  let out = t;
  if (DIRECTIVE_RE.test(out)) out = out.replace(DIRECTIVE_RE, `${eol}${eol}`);
  if (BLOCK_RE.test(out)) out = out.replace(BLOCK_RE, `${eol}${eol}`);
  out = collapseHeaders(out);
  return out.replace(/^\s+/, '');
}

/**
 * 去掉模板开头的 GENERATED 头（插 prelude 前用：prelude 自己带一条，
 * 留着旧的会变成两条，且永远无法被 collapseHeaders 合并 —— 它们被 directive 隔开了）。
 */
export function stripLeadingHeader(t) {
  return t.replace(/^(?:\s*<!--\s*GENERATED by build\/generate\.mjs[^>]*-->\s*)+/, '');
}

/** 把被替换掉的 <content_policy> 还原成原件文本（拿不到原件就原样保留）。 */
export function restoreContentPolicy(t, originalPolicy) {
  if (!originalPolicy) return t;
  if (!/<content_policy>[\s\S]*?<\/content_policy>/.test(t)) return t;
  return t.replace(/<content_policy>[\s\S]*?<\/content_policy>/, originalPolicy);
}

/** 从原版模板里抠出 <content_policy> 块，作为以后还原用的「原件文本」。 */
export function extractContentPolicy(t) {
  const m = typeof t === 'string' ? t.match(/<content_policy>[\s\S]*?<\/content_policy>/) : null;
  return m ? m[0] : null;
}

/** 抠出原版里那段 "IMPORTANT: Assist with authorized security testing…"（切回 light 时还原用）。 */
export function extractSecurityLine(t) {
  const m = typeof t === 'string'
    ? t.match(/IMPORTANT: Assist with authorized security testing[\s\S]*?(?=\nIMPORTANT: You must NEVER generate|\r?\n\r?\n|$)/)
    : null;
  return m ? m[0] : null;
}
