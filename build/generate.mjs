#!/usr/bin/env node
/**
 * 单一来源构建：contract/ → 所有注入载荷。
 * 只有 contract/00-core.md 是权威正文；其余文件全部是派生指针/最小重锚。
 * 用法：node build/generate.mjs [--check]   --check 只比对不写。
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const C = path.join(ROOT, 'contract');
const P = path.join(C, 'pointers');
const PLUGIN = path.join(ROOT, 'package', 'marketplace', 'plugins', 'dsh-purge');
const HEADER = '<!-- GENERATED by build/generate.mjs — 修改请改 contract/ 后重跑 npm run build -->\n\n';
const CHECK = process.argv.includes('--check');

// [源文件, 目标文件, 是否加 GENERATED 头]
const MAP = [
  [path.join(C, '00-core.md'),            path.join(PLUGIN, 'fragments', '00-purge-core.md'),        false],
  [path.join(C, 'host-notes.md'),         path.join(PLUGIN, 'fragments', '10-workbuddy-host.md'),    true],
  [path.join(P, 'anchor.md'),             path.join(PLUGIN, 'fragments', '20-anchor.md'),            true],
  [path.join(P, 'perturn.md'),            path.join(PLUGIN, 'fragments', '30-perturn.md'),           true],
  [path.join(P, 'prelude.txt'),           path.join(PLUGIN, 'host', 'prelude.txt'),                  true],
  [path.join(P, 'policy.txt'),            path.join(PLUGIN, 'host', 'content-policy-replacement.txt'), true],
  [path.join(P, 'tail.md'),               path.join(PLUGIN, 'host', 'tail-append.md'),               true],
];
for (const m of ['hy', 'deepseek', 'mimo']) {
  MAP.push([path.join(P, `turn.${m}.md`),    path.join(PLUGIN, 'prompts', `${m}.turn.md`),    true]);
  MAP.push([path.join(P, `session.${m}.md`), path.join(PLUGIN, 'prompts', `${m}.session.md`), true]);
}

let drift = 0;
for (const [src, dst, header] of MAP) {
  const body = fs.readFileSync(src, 'utf8');
  const want = (header ? HEADER : '') + body;
  const cur = fs.existsSync(dst) ? fs.readFileSync(dst, 'utf8') : null;
  if (cur === want) { console.log(`ok    ${path.relative(ROOT, dst)}`); continue; }
  drift += 1;
  if (CHECK) { console.log(`DRIFT ${path.relative(ROOT, dst)}`); continue; }
  fs.mkdirSync(path.dirname(dst), { recursive: true });
  fs.writeFileSync(dst, want, 'utf8');
  console.log(`write ${path.relative(ROOT, dst)}`);
}
console.log(`generated=${MAP.length} drift=${drift}`);
if (CHECK && drift) process.exit(1);
